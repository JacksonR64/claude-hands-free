import Foundation
import SQLite3

func panelSelfTests() {
    assert(demo, "Run tests with --demo to disable real IPC")
    assert(voiceIntent("Okay next session") == .next)
    assert(voiceIntent("Okay Claude, move to the printers session") == .select("printers"))
    assert(voiceIntent("Switch to Home Assistant") == .select("home assistant"))
    assert(voiceIntent("Next session button needs more contrast") == .dictate("Next session button needs more contrast"))
    assert(voiceIntent("yes") == .dictate("yes"))
    assert(voiceIntent("approve action") == .approve)
    assert(voiceIntent("stop speaking") != voiceIntent("stop working"))
    let candidates = [VoiceCandidate(id: "a", names: ["Printer calibration"]), VoiceCandidate(id: "b", names: ["Printer queue"])]
    assert(matchingSessions("printer", candidates: candidates).count == 2)
    assert(matchingSessions("printer calibration", candidates: candidates) == ["a"])
    assert(matchingSessions("print", candidates: candidates).isEmpty)
    let pin = SpeechDestination(session: "a", instance: "first", request: "q-1")
    assert(!destinationIsCurrent(pin, session: "a", instance: "second", request: "q-1"))
    assert(!destinationIsCurrent(pin, session: "a", instance: "first", request: "q-2"))

    var visibility = PanelPresentation()
    assert(visibility.mode == .menuBar && !visibility.expanded)
    visibility.tick(events: ["first"], now: 1, pointerInside: false, autoExpand: false, autoCollapse: true)
    assert(!visibility.expanded)
    visibility.tick(events: ["second"], now: 2, pointerInside: false, autoExpand: true, autoCollapse: true)
    assert(visibility.expanded)
    visibility.collapse()
    visibility.tick(events: ["second"], now: 3, pointerInside: false, autoExpand: true, autoCollapse: true)
    assert(!visibility.expanded, "The same event must not reopen a dismissed panel")
    visibility.hide()
    visibility.tick(events: ["third"], now: 4, pointerInside: false, autoExpand: true, autoCollapse: true)
    assert(!visibility.expanded && visibility.hidden, "Hide wins even over a new event")
    visibility.mode = .edge; visibility.show(at: 5)
    visibility.tick(events: ["third"], now: 20, pointerInside: true, autoExpand: false, autoCollapse: true)
    assert(visibility.expanded)
    visibility.tick(events: ["third"], now: 29, pointerInside: false, autoExpand: false, autoCollapse: true)
    assert(!visibility.expanded && !visibility.hidden)
    visibility.show(at: 100)
    visibility.tick(events: ["third"], now: 101, pointerInside: false, autoExpand: false, autoCollapse: true)
    assert(visibility.expanded, "Untouched, it waits two seconds")
    visibility.tick(events: ["third"], now: 102.1, pointerInside: false, autoExpand: false, autoCollapse: true)
    assert(!visibility.expanded, "...then tucks away")
    visibility.show(at: 200)
    visibility.tick(events: ["third"], now: 200.5, pointerInside: true, autoExpand: false, autoCollapse: true)
    visibility.tick(events: ["third"], now: 201, pointerInside: false, autoExpand: false, autoCollapse: true)
    assert(visibility.expanded, "After hovering out it keeps a short grace")
    visibility.tick(events: ["third"], now: 201.6, pointerInside: false, autoExpand: false, autoCollapse: true)
    assert(!visibility.expanded, "...of about a second")
    assert(voiceDir != dir && voiceDir.hasSuffix("conversation-demo"), "Sandbox audio cannot enter the live transcript log")
    assert(startsWithWake("Okay Claude, tell it hello") && !startsWithWake("tell it hello") && startsWithWake("okay claude"))
    assert(withoutWake("Okay, Claude, tell it hello") == "tell it hello" && withoutWake("okay claude") == "")
    assert(voiceIntent("next session") == .next, "Commands need no wake phrase")
    assert(voiceIntent("okay Claude, dictate") == .startDictation && voiceIntent("start dictation") == .startDictation)
    do {   // Handy's history database: newest transcript after a known id, post-processed text preferred
        let tmp = NSTemporaryDirectory() + "handy-test-\(UUID().uuidString)"
        try FileManager.default.createDirectory(atPath: tmp, withIntermediateDirectories: true)
        var db: OpaquePointer?
        assert(sqlite3_open(tmp + "/history.db", &db) == SQLITE_OK)
        sqlite3_exec(db, "CREATE TABLE transcription_history (id INTEGER PRIMARY KEY AUTOINCREMENT, file_name TEXT, timestamp INTEGER, saved BOOLEAN, title TEXT, transcription_text TEXT, post_processed_text TEXT, post_process_prompt TEXT, post_process_requested BOOLEAN);", nil, nil, nil)
        sqlite3_close(db)
        let saved = handySupport; handySupport = tmp; defer { handySupport = saved }
        assert(handyLastID() == 0 && handyTranscript(after: 0) == nil)
        sqlite3_open(tmp + "/history.db", &db)
        sqlite3_exec(db, "INSERT INTO transcription_history (file_name, timestamp, saved, title, transcription_text, post_processed_text, post_process_requested) VALUES ('a', 1, 0, 't', 'first message', NULL, 0), ('b', 2, 0, 't', 'raw words', 'Cleaned words.', 0);", nil, nil, nil)
        sqlite3_close(db)
        assert(handyLastID() == 2)
        assert(handyTranscript(after: 0)?.text == "Cleaned words." && handyTranscript(after: 1)?.id == 2 && handyTranscript(after: 2) == nil)
    } catch { assertionFailure("\(error)") }
    assert(voiceIntent("stop listening") == .stopListening)
    assert(voiceIntent("read again") == .readAgain)
    assert(!shouldFinishSpeech(hasTranscript: false, unchangedFor: 10, quietFor: 10))
    assert(!shouldFinishSpeech(hasTranscript: true, unchangedFor: 0.8, quietFor: 2))
    assert(shouldFinishSpeech(hasTranscript: true, unchangedFor: 1, quietFor: 0.7))
    assert(!shouldFinishSpeech(hasTranscript: true, unchangedFor: 1.5, quietFor: 0))
    assert(shouldFinishSpeech(hasTranscript: true, unchangedFor: 1.9, quietFor: 0), "Background noise must not stall a stable recognised answer")
    assert(normalizedInputLevel(-100) == 0 && normalizedInputLevel(0) == 1)
    assert(normalizedInputLevel(.nan) == 0)
    assert(isCurrentPlayback(PlaybackSnapshot(phase: "speaking", ts: 10_000), now: 11))
    assert(!isCurrentPlayback(PlaybackSnapshot(phase: "paused", ts: 10_000), now: 11))
    assert(!isCurrentPlayback(PlaybackSnapshot(phase: "speaking", ts: 10_000), now: 23), "Dead sessions cannot mute the microphone indefinitely")
    assert(!isCurrentPlayback(PlaybackSnapshot(phase: "speaking", ts: 30_000), now: 11))
    let sound = AudioSnapshot(ts: 10, lastBufferAt: 10, db: -32, peakDB: -20, frames: 2048, input: "Test microphone", state: "listening")
    func phase(_ enabled: Bool = true, _ speaking: Bool = false, _ recognizing: Bool = false,
               _ failed: Bool = false, _ sample: AudioSnapshot? = sound, _ now: Double = 10) -> MicrophonePhase {
        microphonePhase(enabled: enabled, speaking: speaking, recognizing: recognizing, failed: failed,
            startedAt: 9, snapshot: sample, now: now)
    }
    assert(phase(false) == .off)
    assert(phase(false, true) == .speaking, "An off confirmation can still be spoken")
    assert(phase(true, false, false, true) == .error)
    assert(phase(true, false, false, false, nil) == .starting)
    assert(phase(true, false, false, false, sound, 20) == .noAudio, "Stale input must not look like a working microphone")
    assert(phase() == .input)
    assert(phase(true, false, true) == .recognizing)
    let silent = AudioSnapshot(ts: 10, lastBufferAt: 10, db: -100, peakDB: -100, frames: 2048, input: "Test", state: "listening")
    assert(phase(true, false, false, false, silent) == .quiet)
    let noFrames = AudioSnapshot(ts: 10, lastBufferAt: 0, db: -100, peakDB: -100, frames: 0, input: "Test", state: "listening")
    assert(phase(true, false, false, false, noFrames) == .noAudio)
    let retry = AudioSnapshot(ts: 10, lastBufferAt: 10, db: -32, peakDB: -20, frames: 2048, input: "Test", state: "retrying")
    assert(phase(true, false, false, false, retry) == .retrying)
    assert(!demoTrialExpired(isDemo: true, listening: true, startedAt: 10, now: 129))
    assert(demoTrialExpired(isDemo: true, listening: true, startedAt: 10, now: 130))
    assert(!demoTrialExpired(isDemo: false, listening: true, startedAt: 10, now: 1000))
    assert(!demoTrialExpired(isDemo: true, listening: false, startedAt: 10, now: 1000))
    let store = Store(); store.loadDemo(); store.allowInterruption = false
    var spoken: [String] = []
    store.demoOutput = { spoken.append($0) }
    store.voice(["event": "ready"])
    assert(spoken.last?.contains("Offline demo") == true)
    assert(spoken.last?.contains("Printers") == true)
    func speak(_ text: String, beforeFinal: (() -> Void)? = nil) {
        let id = UUID().uuidString
        store.voice(["event": "begin", "id": id])
        beforeFinal?()
        store.voice(["event": "final", "id": id, "text": text])
    }
    assert(store.activeID == "printers")
    speak("Okay next session")
    assert(store.activeID == "portfolio")
    speak("Move to the printers session")
    assert(store.activeID == "printers")
    speak("Clear to black")
    assert(store.notice.contains("You answered: Clear to black"))
    assert(store.selected?.pending.isEmpty == true)
    store.demoEvent("permission")
    speak("yes")
    assert(store.selected?.pending.first?.kind == "permission")
    speak("approve action")
    assert(store.selected?.pending.isEmpty == true)
    store.demoEvent("finished")
    assert(store.selected?.ready == true)
    speak("This must not go to another session", beforeFinal: { store.select(store.all[1], read: false) })
    assert(store.notice.contains("changed while you spoke"))
    let previous = store.activeID
    store.voice(["event": "final", "id": "no-begin", "text": "next session"])
    assert(store.activeID == previous)
    speak("Switch to unknown session")
    assert(store.activeID == previous)
    assert(store.notice.contains("No session matches"))
    speak("ask me a question")
    assert(store.selected?.pending.first?.kind == "question")
    speak("read again")
    assert(spoken.last?.contains("Which calibration") == true)
    speak("Grey patches")
    assert(store.selected?.pending.isEmpty == true && spoken.last?.contains("Grey patches") == true)
    speak("show an approval")
    assert(store.selected?.pending.first?.kind == "permission")
    speak("deny action")
    assert(store.selected?.pending.isEmpty == true && spoken.last?.contains("denied") == true)
    speak("finish work")
    assert(store.selected?.ready == true)
    let spokenBeforeBackground = spoken.count
    speak("Tell me about the website")
    assert(store.userCaption == "Tell me about the website")
    assert(spoken.count == spokenBeforeBackground, "Unscripted background speech must not echo aloud")
    assert(!store.assistantCaption.isEmpty)
    var interruptions = 0
    store.demoStop = { interruptions += 1 }
    store.allowInterruption = true
    speak("read again")
    assert(interruptions == 1)
    store.allowInterruption = false
    speak("read again")
    assert(interruptions == 1, "Speaker mode must keep playback gating enabled")
    assert(store.assistantCaption == spoken.last)
    // The numbered waiting list: project threads and sessions that need an answer
    assert(voiceIntent("who's waiting") == .whoIsWaiting && voiceIntent("Okay Claude, who is waiting for me?") == .whoIsWaiting)
    assert(voiceIntent("Reply to number four, yes go ahead and merge it.") == .replyTo(4, "yes go ahead and merge it"))
    assert(voiceIntent("I'll reply to number 4 this that and the other") == .replyTo(4, "this that and the other"))
    assert(voiceIntent("reply to two") == .replyTo(2, "") && voiceIntent("reply to number to sounds good") == .replyTo(2, "sounds good"))
    assert(voiceIntent("tell number three to carry on") == .replyTo(3, "to carry on"))
    assert(voiceIntent("tell 5 people about it") == .dictate("tell 5 people about it"), "A message that mentions a number is still a message")
    assert(voiceIntent("read number two") == .readItem(2) && voiceIntent("open 3") == .openItem(3) && voiceIntent("dismiss number one") == .dismissItem(1))
    assert(voiceIntent("read 3 files in the repo") == .dictate("read 3 files in the repo"))
    assert(voiceIntent("Clear to black") == .dictate("Clear to black") && voiceIntent("read again") == .readAgain)
    let drop = parseDrop(Data(#"{"project":"Shop","project_id":"chan_01ABCDEFGH","thread":"Fix export","thread_id":"cmsg_01ABCDEFGH","text":"Shall I merge?","waiting":true}"#.utf8), now: 100)!
    assert(drop.name == "Shop, Fix export" && drop.url?.absoluteString == "claude://code/project/chan_01ABCDEFGH?thread=cmsg_01ABCDEFGH")
    assert(parseDrop(Data(#"{"project_id":"chan_../../x","text":"hi"}"#.utf8), now: 1) == nil, "Identifiers go into a link, so they must be plain")
    assert(parseDrop(Data(#"{"project_id":"chan_01ABCDEFGH","thread_id":"cmsg_1&x=1","text":"hi"}"#.utf8), now: 1) == nil)
    assert(parseDrop(Data(#"{"project_id":"chan_01ABCDEFGH","waiting":true}"#.utf8), now: 1) == nil, "Nothing to say and waiting is not a message")
    var book = ThreadBook()
    let firstItem = book.apply(drop)
    var other = drop; other.threadID = "cmsg_01ZZZZZZZZ"
    assert(firstItem.number == 1 && book.apply(other).number == 2)
    book.clear(firstItem.id)
    assert(book.waiting.map(\.number) == [2], "An answered thread must not renumber the others")
    var third = drop; third.threadID = "cmsg_01YYYYYYYY"
    assert(book.apply(third, alsoUsed: [1]).number == 3, "Sessions share the numbers")
    other.text = "New question"
    assert(book.apply(other).number == 2 && book.waiting.first?.text == "New question")
    other.waiting = false
    assert(book.apply(other).number == 0 && book.waiting.map(\.number) == [3])
    assert(speakable("**Done** see [the PR](https://x.y/z) `code`") == "Done see the PR code")
    store.demoEvent("quiet")
    store.book = ThreadBook(); store.book.apply(drop)
    speak("who's waiting")
    assert(spoken.last?.contains("1 waiting") == true && spoken.last?.contains("Shop, Fix export") == true)
    speak("read number one")
    assert(spoken.last?.contains("Shall I merge") == true)
    speak("reply to number nine go ahead")
    assert(spoken.last?.contains("no number 9") == true && store.book.waiting.count == 1)
    speak("reply to number one")
    assert(store.replyTarget?.number == 1 && store.book.waiting.count == 1)
    speak("Yes, merge it")
    assert(store.replyTarget == nil && store.book.waiting.isEmpty, "The next utterance answers the armed number")
    store.book.apply(drop)
    speak("Reply to number one, yes merge it")
    assert(store.book.waiting.isEmpty && store.notice.contains("Nothing was sent"))
    store.demoEvent("question"); store.refresh()
    store.book.apply(drop, alsoUsed: Set(store.sessionNumbers.values))
    assert(Set(store.waitingRows.map(\.number)) == [1, 2], "A session question and a thread share one list")
    store.demoEvent("quiet"); store.refresh(); store.book = ThreadBook()
    var microphoneStopped = false
    store.voiceChanged = { microphoneStopped = true }
    store.settings.voice = true
    speak("stop listening")
    assert(microphoneStopped && !store.settings.voice)
    assert(spoken.last == "Microphone off.")
    store.settings.voice = true; microphoneStopped = false
    store.voice(["event": "error", "text": "Test permission denied"])
    assert(microphoneStopped && !store.settings.voice)
    let count = spoken.count
    store.voice(["event": "final", "id": "unbound", "text": "approve action"])
    assert(spoken.count == count, "Unbound speech must not produce a spoken response")
    print("Voice parsing, ambiguity, request identity and full panel routing checks passed")
}
